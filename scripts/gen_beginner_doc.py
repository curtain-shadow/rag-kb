h1("九、阶段 7｜微调阶段（最难）：不靠云端，自己「教」一个本地模型")

label("【这一阶段要做什么】")
para("前面一直用云端大模型。这一步不再依赖云端，而是用一个本地的小模型，用少量数据把它「教」会带引用回答。")

label("【具体怎么做】")
step("造训练数据：用云端模型「出题」并生成带引用的答案，但每条引用都校验「确实存在于资料里」，不合格就丢掉。")
step("抽象模型接口：先重构代码，让「云端模型」和「本地模型」能一键切换，否则本地模型接不进现有流水线。")
step("LoRA 微调：不重训整个模型，只训练一小部分「补丁」参数，用 8GB 的显卡也能做。")

label("【要注意什么】")
bullet("**数据质量第一**：如果训练数据里的引用是编的，模型就学会了「编引用」。所以每条的引用都要校验真实存在。")
bullet("**显存不够会 OOM（最大的坑）**：8GB 卡上微调直接爆显存崩溃。排查到最后，是底层一个「注意力计算内核」默认开了省事模式、把中间结果全摊开导致显存爆炸。关掉它走另一条路径后，峰值从 7.9GB 降到 5.2GB，才跑起来。这种「底层细节卡死人」的坑，是真实项目里最常见的。")

label("【用到的知识点（通俗解释）】")
bullet("**微调（Fine-tune）**：在一个「已经读过很多书」的通用模型基础上，再喂一点「专业课资料」，让它更擅长某件事。")
bullet("**LoRA**：微调时不必重写整本书，只在书页边加「便利贴」（少量参数），省时省显存。")
bullet("**合成数据**：用大模型自己「出题 + 写答案」，凑出训练材料。")
bullet("**OOM（Out Of Memory）**：显存「爆仓」，程序跑不动直接崩。")

summary("这是整个项目最重、最吃基本功的一步——既要懂数据、又要能啃底层显存的坑。")

