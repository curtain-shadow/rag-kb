# 五、阶段3
# ============================================================
h1("五、阶段 3｜第 3 周：找到之后怎么「答得准」——重排 + 带引用生成")

label("【这一阶段要做什么】")
para("上一阶段是「粗选」（先捞一批候选），这一阶段是「精选」：把粗选出来的片段精挑细选，再让大模型只依据这些资料、带出处地回答。")

label("【具体怎么做】")
step("重排：用一个「更仔细」的模型（Cross-Encoder），把问题和候选片段「放在一起」逐条比对，精排出最相关的 4 段。")
step("生成：把这 4 段编上号 [1][2][3][4] 塞进提示词，让大模型回答。")
step("在系统提示词里定死两条「铁律」：① 每句话的依据要在句末标 [1][2] 这样的引用；② 资料里没有的，明确说「资料不足」，不许编造。")

label("【要注意什么】")
bullet("**为什么重排只能对「粗选后的前几名」做，不能全库做？** 因为这种「仔细比对」的模型要把问题和每个片段拼接后一起算，是一对一慢慢比，全库几万个片段跑不动。所以它是「第二轮精挑」，不是「第一轮海选」。")
bullet("**为什么要用提示词定「铁律」？** 大模型天生有「编造」的毛病（资料没有也敢瞎说）。用提示词明文规定「只依据资料、资料不足就直说」，能大幅减少胡说八道。")

label("【用到的知识点（通俗解释）】")
bullet("**重排（Rerank）**：第一轮像「海选」，第二轮像「面试官当面深聊」，把候选和问题放一起仔细比。")
bullet("**大模型（LLM）**：一个读了海量文字的机器，只会「根据上文预测下一个字」，预测得准就显得「会说话」。它本质是统计，不是真的理解。")
bullet("**提示词（Prompt）**：给大模型下的「指令/注意事项」，像给实习生交代任务时列的清单。")
bullet("**引用（Citation）**：答案里的 [1][2]，像论文脚注，标明这句话出自哪段资料。")

summary("「粗选 + 精选」两步走 + 「铁律提示词」，是让答案又准又不瞎编的关键。")

