h1("七、阶段 5｜第 5 周：从「能跑」到「能上量」（向量库升级）")

label("【这一阶段要做什么】")
para("数据量小的时候，怎么检索都行；数据量一大，就要换更聪明的检索后端，而且要「重启不丢」。")

label("【具体怎么做】")
step("把向量存储从 faiss（暴力全扫）升级到 Milvus（用 HNSW 图索引做「近似最近邻」+ 落盘持久化）。")
step("保持接口不变（鸭子类型），一行代码就能在两个后端之间切换，业务代码零改动。")

label("【要注意什么】")
bullet("**为什么要升级？** faiss 的暴力全扫是「每次查询都从头到尾比一遍」，数据一多就慢，而且索引只在内存里、一关程序就丢。Milvus 用「索引」提前建好目录，查得快，还能存硬盘。")
bullet("**升级要「无感」**：换后端不该改业务代码。用统一的接口把变化隔离起来，这是工程上的好习惯。")

label("【用到的知识点（通俗解释）】")
bullet("**近似最近邻（ANN）**：不必挨个比，像图书馆先给书分类上架，找书时直奔那一排书架。")
bullet("**索引**：提前建好的「目录」，查得快。")
bullet("**持久化 / 落盘**：存到硬盘，重启不丢（内存里的东西一关机就没了）。")

summary("这一阶段体现了「工程化」思维：让系统在数据变多时依然快、依然稳。")

