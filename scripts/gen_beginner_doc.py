h1("八、阶段 6｜评测阶段：怎么证明它「真的好」")

label("【这一阶段要做什么】")
para("前面都是「感觉它挺好」，这一步用数据说话：造一份「考卷 + 标准答案」，给系统打分。")

label("【具体怎么做】")
