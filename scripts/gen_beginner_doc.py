h1("三、阶段 1｜第 1 周：把文档变成「能查找的碎片」（解析 + 分块）")

label("【这一阶段要做什么】")
para("系统要「查资料」，前提是资料得是它「读得懂、找得到」的形态。这一步就是把各种格式的文档统一读进来，再切成大小合适的「碎片」。")

label("【具体怎么做】")
step("解析：写一个「注册式」的解析器——按文件后缀名自动分派。PDF 走 PDF 解析器、Word 走 Word 解析器、纯文本走文本解析器，最后统一变成一份「纯文字」。")
step("分块：把长文档剪成小段。这里有个关键设计叫「父子分块」——剪出短的「子块」（约 512 字）用来检索，长的「父块」（约 1536 字）用来喂给大模型回答，两者用编号关联。")

label("【要注意什么】")
para("一个新手最容易问的问题：为什么不直接把一大段当一块？答案是——")
bullet("**向量会被长文本「稀释」**：一句话埋进一大段里，它的意思就被平均掉了，检索时反而找不到。就像一张大合影里找人脸，比单人证件照难找得多。")
bullet("所以用「短子块去检索」（找得准）+「长父块去回答」（内容全），两头都兼顾。")

label("【用到的知识点（通俗解释）】")
bullet("**解析（Parsing）**：把 PDF/Word 这些「给人看排版」的文件，翻译成「程序能读的纯文字」，类似把扫描件 OCR 成可编辑文本。")
bullet("**分块（Chunking）**：把长文章剪成一张张小纸条，方便逐条查找。")
bullet("**向量 / 词嵌入（Embedding）**：把一句话变成一串数字（坐标），意思相近的话坐标也挨得近。就像把每个词摆在一张大地图上，「苹果」和「iPhone」靠在一起。")

summary("把「文档」变成「能检索的碎片」，是整条流水线的第一环，也是后面检索的地基。")

