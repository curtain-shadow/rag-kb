h1("四、阶段 2｜第 2 周：怎么「找得到」——混合检索")

label("【这一阶段要做什么】")
para("让系统能从一大堆碎片里，快速找出和问题最相关的几块。这一步是 RAG 的「R」（检索），是整个项目的心脏。")

label("【具体怎么做】")
step("走两条路，同时检索，各取前 20 名：")
bullet("**稠密检索（语义路）**：用向量模型把问题和碎片都变成坐标，找坐标最接近的——擅长理解「意思相近」（同义词、换种说法）。")
bullet("**稀疏检索（关键词路）**：用 BM25 按「关键词出现频率」精确匹配——擅长命中「专有名词、精确关键词」。")
step("把两路的候选用 RRF 融合成一个最终排名。")

label("【要注意什么】")
para("两个「为什么」，是面试最常被追问的，提前想清楚：")
bullet("**为什么要「向量 + 关键词」双路？** 向量擅长「懂意思」（你说「苹果手机」它能联想到「iPhone」），但抓不住生僻专有名词；关键词检索恰好能精确命中这些词。两者互补，合起来召回更稳。")
bullet("**为什么融合只看「名次」、不把分数相加？** 因为两路打分的「尺子」完全不一样（一个 0~1，一个 0~几十），没法直接相加。所以像跳水比赛一样——去掉各自分数，只看总排名（RRF）。")

label("【用到的知识点（通俗解释）】")
bullet("**向量检索**：按「意思相近」找，同义词、改写也能命中。")
bullet("**BM25**：按「关键词出现几次、出在哪」打分，精确匹配专用。")
bullet("**分词（jieba）**：中文没有空格，要先切成「我 / 爱 / 北京 / 天安门」，才能数词频。")
bullet("**RRF 融合**：两路只看名次、不比分数的「裁判合议」机制。")

summary("「懂意思」和「精确匹配」两条腿走路，是工业界做检索的标准思路。")

