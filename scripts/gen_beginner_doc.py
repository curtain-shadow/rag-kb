step("用另一个大模型当「裁判」，从三个角度打分：忠实度（答案有没有编造）、相关性（有没有答到点子上）、引用准确率（[i] 标得对不对）。")
step("做消融实验：把系统的某个零件拆掉，看分数掉多少，量化每个零件的贡献。")

label("【要注意什么】")
bullet("**评测集要「语义级」标注**：不能靠「答案里出现某个关键词」来判对错，否则会偏心关键词检索，评测就失真了。")
bullet("**裁判要客观**：用一个独立的模型按固定规则打分，而不是人凭感觉说「还行」。")
bullet("**消融要诚实**：即使结论「不那么漂亮」也要如实写。比如这次实测发现，在小语料下 BM25 的贡献不明显——这是个真实的、有信息量的结论，比吹牛有价值得多。")

label("【用到的知识点（通俗解释）】")
bullet("**评测集**：像「考卷 + 标准答案」，用来给系统打分。")
bullet("**LLM 当裁判（LLM-as-judge）**：用另一个模型当「批卷老师」，按固定规则打分。")
bullet("**消融实验**：控制变量法的对照实验——拆掉一个零件看效果差多少，就知道它贡献多大。")
bullet("**指标（Metric）**：打分规则，比如「忠实度 = 有依据的话占全部话的比例」。")

summary("「用数据说话」是新手和成熟工程师的分水岭——不能只说「感觉不错」，要给出可复现的数字。")

